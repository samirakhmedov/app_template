/// Defines the Android-specific feedback style for haptic feedback.
enum HapticFeedbackType {
  /// Context click feedback.
  contextClick,

  /// Drag start feedback.
  dragStart,

  /// Gesture end feedback.
  gestureEnd,

  /// Gesture start feedback.
  gestureStart,

  /// Text handle move feedback.
  textHandleMove,

  /// Virtual key release feedback.
  virtualKeyRelease,
}
